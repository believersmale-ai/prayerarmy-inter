-- Additive Node backend tables. Existing site_content_* IDs and records are preserved.
CREATE TABLE IF NOT EXISTS site_content_messages (
 id VARCHAR(36) PRIMARY KEY, title VARCHAR(200) NOT NULL, description TEXT NULL,
 link VARCHAR(2000) NULL, media_url VARCHAR(2000) NULL, media_type VARCHAR(10) NULL,
 notes_url VARCHAR(2000) NULL, source VARCHAR(6) NOT NULL DEFAULT 'manual',
 speaker VARCHAR(120) NULL, category VARCHAR(60) NULL, thumbnail_url VARCHAR(2000) NULL,
 is_featured TINYINT NOT NULL DEFAULT 0, created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS site_content_testimonies (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(80) NOT NULL, location VARCHAR(80) NULL,
 testimony TEXT NOT NULL, is_approved TINYINT NOT NULL DEFAULT 0,
 show_name TINYINT NOT NULL DEFAULT 0, created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS site_content_wall_prayers (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(60) NULL, request TEXT NOT NULL,
 prayed_count INT UNSIGNED NOT NULL DEFAULT 0, is_approved TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS site_content_message_comments (
 id VARCHAR(36) PRIMARY KEY, message_id VARCHAR(64) NOT NULL, name VARCHAR(80) NOT NULL,
 comment VARCHAR(1000) NOT NULL, created_at DATETIME NOT NULL,
 KEY comments_message (message_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS site_content_wall_votes (
 prayer_id VARCHAR(64) NOT NULL, voter CHAR(64) NOT NULL, ip CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL, PRIMARY KEY (prayer_id, voter), KEY votes_ip (prayer_id, ip, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS site_content_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, kind VARCHAR(30) NOT NULL,
 label VARCHAR(200) NULL, path VARCHAR(200) NULL, referrer VARCHAR(200) NULL,
 device VARCHAR(10) NULL, created_at DATETIME NOT NULL, KEY events_created (created_at, kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS site_hidden_assets (filename VARCHAR(255) PRIMARY KEY)
 ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS node_config (id TINYINT PRIMARY KEY, data LONGTEXT NOT NULL)
 ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS node_staff_profiles (
 user_id VARCHAR(64) PRIMARY KEY, role VARCHAR(12) NOT NULL, display_name VARCHAR(150) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS node_admin_sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id VARCHAR(64) NULL, passkey_version CHAR(64) NULL,
 expires_at DATETIME NOT NULL, KEY sessions_user (user_id), KEY sessions_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS node_rate_limits (
 k VARCHAR(120) PRIMARY KEY, win BIGINT UNSIGNED NOT NULL, hits INT UNSIGNED NOT NULL,
 touched_at DATETIME NOT NULL, KEY rate_age (touched_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
